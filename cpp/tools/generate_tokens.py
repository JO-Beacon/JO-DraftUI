#!/usr/bin/env python3
"""Generate the C++ design-token header from spec/tokens.json.

The generated header is checked in so consumers do not need Python at build
time. Run this script after changing the spec.
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SPEC = ROOT / "spec" / "tokens.json"
OUT = ROOT / "cpp" / "include" / "jo_draftui" / "tokens_generated.hpp"


def cpp_color(name: str) -> str:
    return f"0xFF{name.lstrip('#').upper()}u"


def main() -> None:
    data = json.loads(SPEC.read_text(encoding="utf-8"))
    shape = data["shape"]
    space = data["space"]
    fonts = data["fonts"]
    type_ = data["type"]
    palette = data["palette"]

    lines = [
        "// Generated by cpp/tools/generate_tokens.py from spec/tokens.json.",
        "// Do not edit by hand.",
        "#pragma once",
        "",
        '#include "color.hpp"',
        "",
        "namespace jo::draftui::tokens {",
        "",
        f"inline constexpr float radius = {float(shape['radius'])}f;",
        f"inline constexpr float border_width = {float(shape['borderWidth'])}f;",
        "",
    ]

    for key, value in space.items():
        lines.append(f"inline constexpr float {key} = {float(value)}f;")
    lines.append("")

    lines.extend(
        [
            f'inline constexpr wchar_t sans_family[] = L"{fonts["sans"]}";',
            f'inline constexpr wchar_t serif_family[] = L"{fonts["serif"]}";',
            f'inline constexpr wchar_t mono_family[] = L"{fonts["mono"]}";',
            "",
            f"inline constexpr float body_size = {float(type_['body']['size'])}f;",
            f"inline constexpr float body_height = {float(type_['body']['height'])}f;",
            f"inline constexpr float meta_size = {float(type_['meta']['size'])}f;",
            f"inline constexpr float meta_height = {float(type_['meta']['height'])}f;",
            "inline constexpr float meta_letter_spacing = "
            f"{float(type_['meta'].get('letterSpacing', 0))}f;",
            f"inline constexpr float code_height = {float(type_['code']['height'])}f;",
            "",
        ]
    )

    for mode in ("dark", "light"):
        p = palette[mode]
        for key in ("bg", "surface", "border", "text", "secondary", "icon", "accent"):
            value = p[key]
            lines.append(
                f"inline constexpr Color {mode}_{key} = "
                f"Color::from_argb({cpp_color(value)});"
            )
        lines.append("")

    lines.append("}  // namespace jo::draftui::tokens")
    lines.append("")

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
